// Start Vite locally; run with PLAYWRIGHT_MODULE set if Playwright is not installed.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const origin = process.env.UI_TEST_ORIGIN || 'http://127.0.0.1:5176'
if (!['localhost', '127.0.0.1'].includes(new URL(origin).hostname)) throw new Error('Use a local preview')

async function checkClip(page, right) {
  const clip = await page.locator('.transformation-before').evaluate(el => getComputedStyle(el).clipPath)
  assert.equal(clip, `inset(0px ${right}% 0px 0px)`, 'The actual before layer must follow the slider, including after upgrade completion')
}
async function main() {
  const browser = await chromium.launch({ headless: true })
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, hasTouch: true })
    await context.addInitScript(() => localStorage.setItem('azul-cookies', JSON.stringify({ analytics: false })))
    const page = await context.newPage()
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(origin)
    await page.waitForTimeout(5500)
    const section = page.locator('.transformation')
    for (const project of ['hello', 'aspire']) {
      await section.getByRole('button', { name: project === 'hello' ? /01Hello You/ : /02Aspire/ }).click()
      await section.getByRole('button', { name: 'Watch the upgrade', exact: true }).click()
      await section.getByRole('button', { name: 'Upgrade website', exact: true }).click()
      await page.waitForSelector('.transformation-phase--done')
      // Reproduce the reported bug: use the player CTA, not the toolbar.
      await section.locator('.transformation-player button').click()
      await checkClip(page, 50)
      const slider = section.getByRole('slider')
      await slider.focus()
      await slider.press('Home'); await checkClip(page, 100)
      await slider.press('End'); await checkClip(page, 0)
      await slider.fill('50')
      await slider.scrollIntoViewIfNeeded()
      const box = await slider.boundingBox()
      await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
      await page.mouse.down()
      await page.mouse.move(box.x + box.width * .8, box.y + box.height / 2, { steps: 10 })
      await page.mouse.up()
      assert.equal(await slider.inputValue(), '80'); await checkClip(page, 20)
      await slider.fill('50')
      await page.waitForFunction(() => { const v = document.querySelector('.transformation video'); return v.readyState >= 3 && v.currentTime > 0 && !v.paused })
      const start = await section.locator('video').evaluate(v => v.currentTime)
      await page.waitForTimeout(300)
      const end = await section.locator('video').evaluate(v => v.currentTime)
      assert.notEqual(start, end, 'The real homepage preview must move')
      await section.getByRole('button', { name: 'Pause video', exact: true }).click()
      assert(await section.locator('video').evaluate(v => v.paused))
      await section.screenshot({ path: `/tmp/azul-${project}-comparison-fixed.png`, style: '.site-header,.skip-link,.cookie-reopen,.ai-pill{visibility:hidden!important}' })
      await section.getByRole('button', { name: 'Play video', exact: true }).click()
    }
    await page.setViewportSize({ width: 390, height: 844 })
    const slider = section.getByRole('slider')
    await slider.scrollIntoViewIfNeeded()
    const box = await slider.boundingBox()
    const cdp = await context.newCDPSession(page)
    const y = box.y + box.height / 2
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: box.x + box.width / 2, y }] })
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: box.x + box.width * .25, y }] })
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    const touchPosition = Number(await slider.inputValue())
    assert(Math.abs(touchPosition - 25) <= 2); await checkClip(page, 100 - touchPosition)
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    await section.screenshot({ path: '/tmp/azul-comparison-mobile-fixed.png', style: '.site-header,.skip-link,.cookie-reopen,.ai-pill{visibility:hidden!important}' })
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.reload()
    await section.getByRole('button', { name: 'Compare designs', exact: true }).click()
    assert(await section.locator('video').evaluate(v => v.paused && !v.getAttribute('src')))
    await section.getByRole('button', { name: 'Play video', exact: true }).click()
    await page.waitForFunction(() => !document.querySelector('.transformation video').paused)
    await page.evaluate(() => localStorage.setItem('azul-lang', 'es'))
    await page.goto(`${origin}/work`)
    await section.getByRole('slider').fill('30'); await checkClip(page, 70)
    assert(await section.getByRole('button', { name: 'Reproducir video', exact: true }).count())
    assert.deepEqual(errors, [])
    console.log('PASS: completed-upgrade CTA regression, both visible layers, pointer/keyboard/touch slider, both homepage videos, pause/play, reduced motion, mobile, Spanish, Work route.')
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
