export function readingMinutes(article) {
  const text = [article.dek, article.takeaway, ...article.sections.flatMap(s => [s.title, ...s.paragraphs]), ...article.checklist].join(' ')
  return Math.max(1, Math.ceil(text.split(/\s+/).length / 200))
}
export function filterInsights(articles, copy, category, query) {
  const normalize = value => value.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase()
  const terms = normalize(query).trim().split(/\s+/).filter(Boolean)
  return articles.filter(article => {
    const text = copy.articles[article.slug]
    const haystack = normalize([text.title, text.dek, ...text.sections.flatMap(s => [s.title, ...s.paragraphs]), copy.filters.find(f => f.value === article.category)?.label || ''].join(' '))
    return (category === 'all' || article.category === category) && terms.every(term => haystack.includes(term))
  })
}
